    #[test]
    fn import_writes_and_unimport_removes_only_generated_files() {
        let root = Tmp::new("import");
        import_into(&root.0, &Pin::builtin()).unwrap();
        let manifest = fs::read_to_string(root.0.join("Cargo.toml")).unwrap();
        assert!(manifest.starts_with(GENERATED));
        assert!(manifest.contains(&format!("rev = \"{DEFAULT_REV}\"")));
        for p in DEFAULT_PATCHED {
            assert!(manifest.contains(&format!("{p} = ")), "{p} is patched");
        }
        let doc: DocumentMut = manifest.parse().expect("the generated manifest is valid TOML");
        assert_eq!(doc["workspace"]["dependencies"]["rune"]["default-features"].as_bool(), Some(false));
        assert!(fs::read_to_string(root.0.join("rust-toolchain.toml")).unwrap().contains("channel = \"1.99.1\""));
        assert!(unimport_from(&root.0).unwrap().contains("removed"));
        assert!(!root.0.join("Cargo.toml").exists() && !root.0.join("rust-toolchain.toml").exists());
        // A hand-written manifest is never overwritten or removed.
        fs::write(root.0.join("Cargo.toml"), "[workspace]\n").unwrap();
        assert!(import_into(&root.0, &Pin::builtin()).is_err());
        assert!(unimport_from(&root.0).is_err());
        assert_eq!(fs::read_to_string(root.0.join("Cargo.toml")).unwrap(), "[workspace]\n");
    }

